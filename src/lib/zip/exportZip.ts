/**
 * Generates the README.md content with explicit manual install instructions
 * reinforcing the "Included in export" mental model (no auto-sync or local execution).
 */
function generateReadmeMarkdown(toolsIncluded: ToolId[]): string {
  return `# Agent Config Studio — Export Package

Generated by **Agent Config Studio** in your browser.
Mental Model: Configurations in this archive are export artifacts. Nothing has been automatically written, synced, or installed on your system.

---

## Manual Installation Instructions

${toolsIncluded
  .map((toolId) => {
    const tool = TOOLS[toolId];
    return `### ${tool.name}

1. **MCP Configuration**:
   - Location: \`${tool.configPathDisplay}\`
   - Inspect: \`export/${toolId}/${tool.format === 'toml' ? 'mcp-config-snippet.toml' : toolId === 'pi' ? 'mcp.json' : toolId === 'claude' ? 'mcp-config-snippet.json' : 'opencode-snippet.json'}\`
   - *Action*: Merge the provided snippet into your existing configuration file, or replace it if starting fresh. Always back up your current configuration first.

2. **System Prompt Directives**:
   - Location: \`${tool.promptPathDisplay}\`
   - Inspect: \`export/${toolId}/${toolId === 'claude' ? 'CLAUDE.md' : 'AGENTS.md'}\`
   - *Action*: Copy this file to \`${tool.promptPathDisplay}\`.

3. **Skills Directory**:
   - Location: \`${tool.skillsPathDisplay}\`
   - Inspect: \`export/${toolId}/skills/\`
   - *Action*: Copy the skill directories into \`${tool.skillsPathDisplay}\`. Each skill folder contains its \`SKILL.md\` and supporting assets.
`;
  })
  .join('\n---\n\n')}

## Security Notice
- Review all environment variables and secrets before running any agent commands.
- Never commit unredacted personal credentials to public repositories.
`;
}

/**
 * Builds the complete Workspace Bundle ZIP matching §6 exact folder layout.
 */
export async function buildWorkspaceZip(options: {
  servers: McpServer[];
  skills: Skill[];
  prompts: PromptPreset[];
  selectedTools?: ToolId[];
  maskSecrets?: boolean;
}): Promise<Blob> {
  const {
    servers,
    skills,
    prompts,
    selectedTools = ['claude', 'codex', 'pi', 'opencode'],
    maskSecrets = true
  } = options;

  const zip = new JSZip();
  const root = zip.folder('export') || zip;

  // Add README.md
  root.file('README.md', generateReadmeMarkdown(selectedTools));

  for (const toolId of selectedTools) {
    const toolFolder = root.folder(toolId);
    if (!toolFolder) continue;

    // 1. MCP snippet
    if (toolId === 'claude') {
      const { jsonString } = serializeClaudeMcp(servers, { maskSecrets, fullEnvelope: true });
      toolFolder.file('mcp-config-snippet.json', jsonString);
    } else if (toolId === 'codex') {
      const { tomlString } = serializeCodexMcp(servers, { maskSecrets });
      toolFolder.file('mcp-config-snippet.toml', tomlString);
    } else if (toolId === 'pi') {
      const { jsonString } = serializePiMcp(servers, { maskSecrets, fullEnvelope: true });
      toolFolder.file('mcp.json', jsonString);
    } else if (toolId === 'opencode') {
      const { jsonString } = serializeOpenCodeMcp(servers, { maskSecrets, fullEnvelope: true });
      toolFolder.file('opencode-snippet.json', jsonString);
    }

    // 2. Active Prompts
    const toolPrompts = prompts.filter((p) => p.tool === toolId && p.isActive);
    const systemPrompt = toolPrompts.find((p) => p.type === 'system');

    if (toolId === 'claude') {
      if (systemPrompt) {
        toolFolder.file('CLAUDE.md', systemPrompt.content);
      }
    } else {
      if (systemPrompt) {
        toolFolder.file('AGENTS.md', systemPrompt.content);
      }
    }

    // Pi extras
    if (toolId === 'pi') {
      const appendPrompt = toolPrompts.find((p) => p.type === 'append_system');
      if (appendPrompt) {
        toolFolder.file('APPEND_SYSTEM.md', appendPrompt.content);
      }
    }

    // 3. Enabled Skills
    const enabledSkills = skills.filter((s) => s.toolsEnabled[toolId]);
    if (enabledSkills.length > 0) {
      const skillsFolder = toolFolder.folder('skills');
      if (skillsFolder) {
        for (const skill of enabledSkills) {
          const singleSkillFolder = skillsFolder.folder(skill.slug);
          if (singleSkillFolder) {
            for (const file of skill.files) {
              singleSkillFolder.file(file.path, file.content);
            }
          }
        }
      }
    }
  }

  return zip.generateAsync({ type: 'blob' });
}

/**
 * Builds a standalone ZIP for a single Skill directory.
 */
export async function buildSkillZip(skill: Skill): Promise<Blob> {
  const zip = new JSZip();
  const folder = zip.folder(skill.slug) || zip;

  for (const file of skill.files) {
    folder.file(file.path, file.content);
  }

  return zip.generateAsync({ type: 'blob' });
}

/**
 * Builds a per-tool ZIP for a single Skill placed under that tool's target skills path.
 */
export async function buildPerToolSkillZip(skill: Skill, toolId: ToolId): Promise<Blob> {
  const zip = new JSZip();
  const targetDirName =
    toolId === 'claude'
      ? '.claude/skills'
      : toolId === 'codex'
        ? '.codex/skills'
        : toolId === 'pi'
          ? '.pi/agent/skills'
          : '.config/opencode/skills';

  const folder = zip.folder(`${targetDirName}/${skill.slug}`) || zip;

  for (const file of skill.files) {
    folder.file(file.path, file.content);
  }

  return zip.generateAsync({ type: 'blob' });
}

/**
 * Unpacks an uploaded ZIP file and extracts skill directories.
 * Guards against directory traversal and unreasonable file sizes.
 */
export async function unpackSkillsFromZip(zipBlob: Blob | File): Promise<Skill[]> {
  const zip = await JSZip.loadAsync(zipBlob);
  const foundSkills: Map<string, { slug: string; files: SkillFile[] }> = new Map();

  // Find all SKILL.md entries
  const fileEntries = Object.keys(zip.files);

  for (const path of fileEntries) {
    // Guard against directory traversal
    if (path.includes('../') || path.startsWith('/') || path.includes('..\\')) {
      continue;
    }

    const zipObj = zip.files[path];
    if (zipObj.dir) continue;

    // Determine directory prefix
    const parts = path.split('/');
    // Check if filename is SKILL.md
    if (parts[parts.length - 1] === 'SKILL.md') {
      const dirSlug = parts.length > 1 ? parts[parts.length - 2] : 'imported-skill';
      if (!foundSkills.has(dirSlug)) {
        foundSkills.set(dirSlug, { slug: dirSlug, files: [] });
      }
    }
  }

  // If no SKILL.md was found in a subfolder, maybe SKILL.md was at root
  if (foundSkills.size === 0 && zip.files['SKILL.md']) {
    foundSkills.set('imported-skill', { slug: 'imported-skill', files: [] });
  }

  // Populate files for each detected skill
  for (const [slug, item] of foundSkills.entries()) {
    for (const [path, zipObj] of Object.entries(zip.files)) {
      if (zipObj.dir) continue;
      // Skip path traversal
      if (path.includes('../') || path.startsWith('/')) continue;

      let relativePath = path;
      if (path.includes(`${slug}/`)) {
        relativePath = path.slice(path.indexOf(`${slug}/`) + slug.length + 1);
      } else if (slug === 'imported-skill' && !path.includes('/')) {
        relativePath = path;
      } else {
        continue;
      }

      if (relativePath) {
        const text = await zipObj.async('text');
        item.files.push({
          path: relativePath,
          content: text
        });
      }
    }
  }

  const resultSkills: Skill[] = [];
  const now = Date.now();

  for (const item of foundSkills.values()) {
    const skillMdFile = item.files.find((f) => f.path === 'SKILL.md');
    let name = item.slug.replace(/[-_]/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
    let description = `Skill imported from ZIP archive (${item.slug})`;

    if (skillMdFile) {
      // Parse basic YAML frontmatter
      const fmMatch = skillMdFile.content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
      if (fmMatch) {
        const fm = fmMatch[1];
        const nameMatch = fm.match(/^name:\s*(.+)$/m);
        const descMatch = fm.match(/^description:\s*(.+)$/m);
        if (nameMatch) name = nameMatch[1].trim().replace(/^['"]|['"]$/g, '');
        if (descMatch) description = descMatch[1].trim().replace(/^['"]|['"]$/g, '');
      }
    }

    resultSkills.push({
      id: item.slug,
      slug: item.slug,
      name,
      description,
      tags: ['imported', 'zip'],
      sourceRepo: 'ZIP Archive',
      files: item.files,
      toolsEnabled: { claude: true, codex: true, pi: true, opencode: true },
      createdAt: now,
      updatedAt: now
    });
  }

  return resultSkills;
}
